fn find(table: &'static [(&'static str, &'static str)], key: &str) -> Option<&'static str> {
    table.iter().find(|(k, _)| *k == key).map(|(_, v)| *v)
}

/// The label language for a reader in `jurisdiction` (English when none is known).
pub fn jurisdiction_language(jurisdiction: &str) -> &'static str {
    find(&JURISDICTION_LANGUAGE, jurisdiction).unwrap_or("en")
}

/// The notice in every requested language we have, English always included.
pub fn disclosure<S: AsRef<str>>(languages: &[S]) -> IndexMap<String, String> {
    let mut out = IndexMap::new();
    for lang in std::iter::once("en").chain(languages.iter().map(AsRef::as_ref)) {
        if !out.contains_key(lang)
            && let Some(text) = find(&DISCLOSURES, lang)
        {
            out.insert(lang.to_string(), text.to_string());
        }
    }
    out
}

/// Prefix a visible label, once. Uses the first language with a label.
pub fn label<S: AsRef<str>>(text: &str, languages: &[S]) -> String {
    for lang in languages.iter().map(AsRef::as_ref).chain(std::iter::once("en")) {
        if let Some(tag) = find(&LABELS, lang) {
            return if text.starts_with(tag) { text.to_string() } else { format!("{tag} {text}") };
        }
    }
    text.to_string()
}

