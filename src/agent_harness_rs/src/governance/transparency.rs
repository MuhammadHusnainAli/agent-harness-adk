/// A machine-readable record that content was AI-generated, and how.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ProvenanceManifest {
    #[serde(default = "content_id")]
    pub content_id: String,
    #[serde(default)]
    pub content_sha256: String,
    #[serde(default = "yes")]
    pub ai_generated: bool,
    #[serde(default = "generator")]
    pub generator: String,
    /// The deploying organisation (GB 45438).
    #[serde(default)]
    pub service_provider: String,
    #[serde(default)]
    pub agent: String,
    #[serde(default)]
    pub models: Vec<String>,
    #[serde(default)]
    pub providers: Vec<String>,
    #[serde(default)]
    pub run_id: String,
    #[serde(default = "now")]
    pub created: f64,
    #[serde(default)]
    pub policy: String,
    #[serde(default)]
    pub labels: Map<String, Value>,
    #[serde(default)]
    pub signature: String,
    #[serde(default)]
    pub key_id: String,
}

impl Default for ProvenanceManifest {
    fn default() -> Self {
        Self {
            content_id: content_id(),
            content_sha256: String::new(),
            ai_generated: true,
            generator: generator(),
            service_provider: String::new(),
            agent: String::new(),
            models: vec![],
            providers: vec![],
            run_id: String::new(),
            created: now(),
            policy: String::new(),
            labels: Map::new(),
            signature: String::new(),
            key_id: String::new(),
        }
    }
}

impl ProvenanceManifest {
    /// A manifest for this text, with its sha256 filled in.
    pub fn for_output(text: &str) -> Self {
        Self { content_sha256: super::sha256_hex(text.as_bytes()), ..Self::default() }
    }

    /// What the signature covers: the manifest as Python's `model_dump_json`
    /// writes it, without `signature` and `key_id` — compact, fields in order,
    /// text as UTF-8.
    pub fn payload(&self) -> Vec<u8> {
        let mut value = serde_json::to_value(self).unwrap_or_default();
        if let Some(m) = value.as_object_mut() {
            m.shift_remove("signature");
            m.shift_remove("key_id");
        }
        serde_json::to_string(&value).unwrap_or_default().into_bytes()
    }

    pub fn sign(&mut self, signer: &dyn Signer) -> &mut Self {
        self.signature = signer.sign(&self.payload());
        self.key_id = signer.key_id();
        self
    }

    /// The signature checks out — and, given the text, the text is the one marked.
    pub fn verify(&self, signer: &dyn Signer, text: Option<&str>) -> bool {
        if let Some(t) = text
            && super::sha256_hex(t.as_bytes()) != self.content_sha256
        {
            return false;
        }
        !self.signature.is_empty() && signer.verify(&self.payload(), &self.signature)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::governance::records::HMACSigner;
    use serde_json::json;

    #[test]
    fn labels_and_disclosures() {
        assert_eq!(label("Hello.", &["zh"]), "\u{3010}AI\u{751f}\u{6210}\u{3011} Hello.");
        assert_eq!(label("[AI-generated] x", &["xx"]), "[AI-generated] x");
        let d = disclosure(&["zh", "en", "xx"]);
        assert_eq!(d.keys().cloned().collect::<Vec<_>>(), vec!["en", "zh"]);
        assert_eq!(jurisdiction_language("ae-difc"), "ar");
    }

    #[test]
    fn manifests_sign_the_bytes_python_signs() {
        let manifest = ProvenanceManifest {
            content_id: "cnt_1".into(),
            service_provider: "Acme".into(),
            agent: "helper".into(),
            models: vec!["m".into()],
            providers: vec!["fake".into()],
            run_id: "run_1".into(),
            created: 1_700_000_000.5,
            policy: "abcd".into(),
            labels: json!({"explicit": true, "implicit": true, "languages": ["zh"]}).as_object().cloned().unwrap(),
            ..ProvenanceManifest::for_output("Hello.")
        };
        assert_eq!(
            String::from_utf8(manifest.payload()).unwrap(),
            r#"{"content_id":"cnt_1","content_sha256":"2d8bd7d9bb5f85ba643f0110d50cb506a1fe439e769a22503193ea6046bb87f7","ai_generated":true,"generator":"agent-harness-adk","service_provider":"Acme","agent":"helper","models":["m"],"providers":["fake"],"run_id":"run_1","created":1700000000.5,"policy":"abcd","labels":{"explicit":true,"implicit":true,"languages":["zh"]}}"#
        );
        let signer = HMACSigner::new(&[b'k'; 32], None).unwrap();
        let mut signed = manifest.clone();
        signed.sign(&signer);
        assert_eq!(signed.signature, "39bf953df59c371fb9c148f90366d13a5ee3ef833aba6e47c443fccd659751a8");
        assert!(signed.verify(&signer, Some("Hello.")) && !signed.verify(&signer, Some("Hello.!")));
    }
}
