"""Telling people it is AI, and marking what AI made.

Two duties recur across the EU AI Act (Art 50), China's labeling measures and
GB 45438-2025, Korea's AI Basic Act, Vietnam's AI law and DIFC Regulation 10:

* **Disclosure** — the person should know they are dealing with an AI system.
  `result.disclosure` carries the notice, in the languages your packs call
  for; your interface decides where to show it.
* **Marking** — generated content should carry a machine-readable mark.
  `result.provenance` is a manifest in the shape C2PA assertions and GB 45438
  implicit labels both need: who generated it, with what, when, a content id
  and a hash of the content. Signed when the governance layer has a signer.

`label_output=True` (the China pack sets it) also puts a visible label in the
text itself.
"""

