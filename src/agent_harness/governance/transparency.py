def disclosure(languages: list[str]) -> dict[str, str]:
    """The notice in every requested language we have, English always included."""
    wanted = list(dict.fromkeys(["en", *languages]))
    return {lang: DISCLOSURES[lang] for lang in wanted if lang in DISCLOSURES}


#: The language a label is written in, by the reader's jurisdiction.
JURISDICTION_LANGUAGE: dict[str, str] = {
    "cn": "zh", "kr": "ko", "jp": "ja", "vn": "vi", "sa": "ar", "ae": "ar", "ae-difc": "ar",
    "ae-adgm": "ar", "qa": "ar", "bh": "ar", "om": "ar", "kw": "ar", "fr": "fr", "de": "de",
    "es": "es",
}


def label(text: str, languages: list[str]) -> str:
    """Prefix a visible label, once. Uses the first language with a label."""
    for lang in [*languages, "en"]:
        tag = LABELS.get(lang)
        if tag:
            return text if text.startswith(tag) else f"{tag} {text}"
    return text


class ProvenanceManifest(BaseModel):
    """A machine-readable record that content was AI-generated, and how."""

    content_id: str = Field(default_factory=lambda: new_id("cnt"))
    content_sha256: str = ""
    ai_generated: bool = True
    generator: str = "agent-harness-adk"
    service_provider: str = ""        # the deploying organisation (GB 45438)
    agent: str = ""
    models: list[str] = Field(default_factory=list)
    providers: list[str] = Field(default_factory=list)
    run_id: str = ""
    created: float = Field(default_factory=time.time)
    policy: str = ""
    labels: dict[str, Any] = Field(default_factory=dict)
    signature: str = ""
    key_id: str = ""

    @classmethod
    def for_output(cls, text: str, **fields: Any) -> ProvenanceManifest:
        return cls(content_sha256=hashlib.sha256(text.encode()).hexdigest(), **fields)

    def payload(self) -> bytes:
        return self.model_dump_json(exclude={"signature", "key_id"}).encode()

    def sign(self, signer: Any) -> ProvenanceManifest:
        self.signature = signer.sign(self.payload())
        self.key_id = signer.key_id
        return self

    def verify(self, signer: Any, text: str | None = None) -> bool:
        if text is not None and hashlib.sha256(text.encode()).hexdigest() != \
                self.content_sha256:
            return False
        return bool(self.signature) and signer.verify(self.payload(), self.signature)
